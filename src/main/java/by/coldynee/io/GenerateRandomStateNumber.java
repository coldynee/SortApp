package by.coldynee.io;

import java.util.Random;

/**
 * Генератор случайных государственных номеров.
 * <p>
 * Формат номера: А123БВ777
 * <ul>
 *     <li>Первая буква из допустимого набора</li>
 *     <li>Три цифры (001-999)</li>
 *     <li>Две буквы из допустимого набора</li>
 *     <li>Код региона (2-3 цифры)</li>
 * </ul>
 * </p>
 */
public class GenerateRandomStateNumber {
    // Допустимые буквы в русских государственных номерах
    private static final String LETTERS = "АВЕКМНОРСТУХ";
    // Коды российских регионов
    private static final String[] REGIONS = {
            "01", "101", "02", "102", "702", "03", "103", "04", "05", "105",
            "06", "07", "08", "09", "109", "10", "11", "111", "12", "13", "113",
            "14", "15", "16", "116", "716", "17", "18", "19", "21", "121", "721",
            "22", "122", "23", "93", "123", "193", "323", "24", "84", "88", "124",
            "25", "125", "725", "26", "126", "27", "28", "29", "30", "31", "32",
            "33", "133", "34", "134", "35", "36", "136", "37", "38", "138", "39",
            "91", "40", "41", "82", "42", "142", "43", "44", "45", "46", "47",
            "147", "48", "49", "50", "90", "150", "190", "750", "790", "250", "51",
            "52", "152", "752", "53", "54", "154", "55", "56", "156", "57", "58",
            "59", "81", "159", "60", "61", "161", "761", "62", "63", "163", "763",
            "64", "164", "65", "66", "96", "196", "67", "68", "69", "70", "71",
            "72", "73", "173", "74", "174", "774", "75", "80", "76", "77", "97",
            "99", "177", "197", "199", "777", "797", "799", "977", "277", "299",
            "78", "98", "178", "198", "278", "798", "79", "83", "85", "86", "186",
            "87", "89", "92", "94", "95", "184", "185", "188"
    };

    private Random random = new Random();

    /**
     * Генерирует случайный государственный номер автобуса.
     *
     * @return строка с государственным номером в формате А123БВ77
     */
    public String randomStateNumber() {
        char letter1 = LETTERS.charAt(random.nextInt(LETTERS.length()));
        int number = random.nextInt(999) + 1;
        char letter2 = LETTERS.charAt(random.nextInt(LETTERS.length()));
        char letter3 = LETTERS.charAt(random.nextInt(LETTERS.length()));
        String region = REGIONS[random.nextInt(REGIONS.length)];
        return String.format("%s%03d%s%s%s", letter1, number, letter2, letter3, region);
    }
}